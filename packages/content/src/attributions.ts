type Attribution =
  | Pick<GeneralQuote, 'category' | 'author'>
  | Pick<BibleVerse, 'category' | 'reference'>;

export function attributionUrl(quote: Attribution): string | undefined {
  const pages = quote.category === 'general' ? AUTHOR_PAGES : BIBLE_BOOK_PAGES;
  const name = quote.category === 'general' ? quote.author : quote.reference.replace(/ \d.*$/, '');
  return Object.hasOwn(pages, name) ? pages[name] : undefined;
}
